namespace InkPlay.Services.Agents;

public static class PromptTemplates
{
    public static string GetWriterGenrePrompt(string genre)
    {
        return genre switch
        {
            "玄幻" => @"【玄幻类型写作指南】
- 力量体系：严格遵循已设定的修炼/力量体系，不随意突破境界限制
- 战斗场面：注重招式描写、力量对撞的视觉感，避免空洞的'强大'描述
- 境界描述：通过对手的反应、环境变化来侧面烘托实力差距
- 世界观：尊重已建立的种族、势力、地理设定
- 禁忌：不要出现现代科技元素，不要破坏已设定的力量上限",

            "都市" => @"【都市类型写作指南】
- 写实对话：使用自然、接地气的现代口语，避免文绉绉的表达
- 现代场景：准确描写现代城市生活细节（手机、外卖、地铁等）
- 情感细腻：注重人物内心活动和微妙的情感变化
- 社会关系：真实呈现职场、家庭、朋友间的复杂关系
- 禁忌：不要出现超自然元素（除非设定允许），不要脱离现实逻辑",

            "悬疑" => @"【悬疑类型写作指南】
- 线索管理：确保每条线索都有始有终，不要遗留未解释的细节
- 伏笔布局：在看似无关的细节中埋下关键信息
- 节奏控制：通过信息的逐步释放维持紧张感
- 逻辑严密：推理过程必须经得起推敲，不要依赖巧合
- 禁忌：不要在没有铺垫的情况下突然揭示凶手，不要使用超自然解释（除非设定允许）",

            "仙侠" => @"【仙侠类型写作指南】
- 修仙体系：严格遵循境界划分，修炼突破需要合理的机缘和积累
- 法术描写：注重法术的视觉效果和威力表现
- 天地法则：尊重已设定的天道、劫数、因果规则
- 古风语言：适当使用文言化的表达，但不要过度影响可读性
- 禁忌：不要出现现代科技元素，不要随意打破境界壁垒",

            "历史" => @"【历史类型写作指南】
- 史实尊重：重大历史事件和人物不能随意篡改
- 时代细节：准确呈现当时的服饰、饮食、礼仪、建筑
- 语言风格：使用符合时代的对话风格，但保持可读性
- 权谋描写：注重政治博弈的复杂性和人性的多面性
- 禁忌：不要出现明显的时代穿越元素（除非设定允许）",

            "言情" => @"【言情类型写作指南】
- 情感发展：感情线需要循序渐进，不要突兀的转变
- 互动细节：通过小动作、眼神、语气展现人物间的化学反应
- 矛盾冲突：情感障碍要合理，不要依赖误会推动剧情
- 人物魅力：每个角色都要有独特的性格魅力
- 禁忌：不要出现逻辑不通的'恋爱脑'行为，不要过度虐心",

            "科幻" => @"【科幻类型写作指南】
- 科技设定：遵循已建立的科技体系，不要随意添加新能力
- 世界观：尊重已设定的宇宙规则、种族设定
- 技术细节：适当解释技术原理，但不要变成科普文
- 人性探讨：科幻背景下的人性思考是核心价值
- 禁忌：不要出现明显的科学错误，不要破坏已设定的科技上限",

            _ => string.Empty
        };
    }

    public static string GetAuditorGenrePrompt(string genre)
    {
        return genre switch
        {
            "玄幻" => @"【玄幻专项检查】
- 力量体系一致性：角色实力是否符合其境界设定
- 战斗逻辑：战斗结果是否合理，有没有以弱胜强却无合理解释
- 世界观遵守：是否违反已设定的种族/势力规则",

            "都市" => @"【都市专项检查】
- 现实逻辑：情节是否符合现实社会的运行规则
- 对话自然度：对话是否像真实的人在说话
- 细节准确性：现代生活细节是否准确",

            "悬疑" => @"【悬疑专项检查】
- 线索完整性：所有线索是否都有交代
- 推理逻辑：推理过程是否严密，有没有逻辑漏洞
- 公平性：读者是否能通过已有信息推导出真相",

            "仙侠" => @"【仙侠专项检查】
- 境界一致性：角色实力是否符合修炼境界
- 天道规则：是否违反已设定的天道/劫数规则
- 法术逻辑：法术使用是否符合已建立的体系",

            "历史" => @"【历史专项检查】
- 史实准确性：重大历史事件是否准确
- 时代符合度：细节是否符合所描写的时代
- 人物一致性：历史人物的行为是否符合史书记载的性格",

            "言情" => @"【言情专项检查】
- 情感合理性：感情发展是否自然合理
- 人物魅力：角色是否保持了独特的性格魅力
- 矛盾合理性：情感冲突是否有说服力",

            "科幻" => @"【科幻专项检查】
- 科技一致性：是否违反已建立的科技体系
- 世界观遵守：是否破坏已设定的宇宙规则
- 科学性：是否有明显的科学错误",

            _ => string.Empty
        };
    }
}
